// Reading raw DNA files: the formats people download, missing calls, zipped files, and that only the asked-for
// rsIDs are kept.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { deflateRawSync, crc32 } from 'node:zlib';
import { extractPanel, fromString, normaliseGenotype } from '../src/genome/parse.mjs';
import { isZip, openRawDataInZip, chunksOf } from '../src/genome/unzip.mjs';

const WANT = ['rs4988235', 'rs671', 'rs17822931'];

test('23andMe layout: comments, a header, CRLF line ends, "--" for no call', async () => {
  const text = [
    '# This data file generated by a test',
    '# rsid\tchromosome\tposition\tgenotype',
    'rs1\t1\t100\tAA',
    'rs4988235\t2\t136608646\tGA',
    'rs671\t12\t112241766\t--',
    'rs9\t3\t5\tCT',
  ].join('\r\n');
  const r = await extractPanel(fromString(text, 7), WANT);
  assert.equal(r.rows, 4);
  assert.equal(r.found.size, 2);
  assert.equal(r.found.get('rs4988235').genotype, 'AG', 'sorted');
  assert.equal(r.found.get('rs671').genotype, null, 'no call');
  assert.equal(r.found.has('rs17822931'), false, 'absent');
});

test('AncestryDNA layout: two allele columns, "0 0" for no call, build from the header', async () => {
  const text = [
    '#AncestryDNA raw data download',
    '#genotypes on the plus strand, human reference build 37 (GRCh37)',
    'rsid\tchromosome\tposition\tallele1\tallele2',
    'rs4988235\t2\t136608646\tA\tA',
    'rs671\t12\t112241766\t0\t0',
    'rs17822931\t16\t48258198\tT\tC',
  ].join('\n');
  const r = await extractPanel(fromString(text), WANT);
  assert.equal(r.format, 'ancestrydna');
  assert.equal(r.build, 'build 37');
  assert.equal(r.found.get('rs4988235').genotype, 'AA');
  assert.equal(r.found.get('rs671').genotype, null);
  assert.equal(r.found.get('rs17822931').genotype, 'CT');
});

test('MyHeritage / FamilyTreeDNA layout: quoted CSV', async () => {
  const text = ['# MyHeritage DNA raw data.', 'RSID,CHROMOSOME,POSITION,RESULT', '"rs4988235","2","136608646","GG"', '"rs17822931","16","48258198","--"'].join('\n');
  const r = await extractPanel(fromString(text), WANT);
  assert.equal(r.found.get('rs4988235').genotype, 'GG');
  assert.equal(r.found.get('rs17822931').genotype, null);
});

test('genotype normalisation refuses what is not a call', () => {
  assert.equal(normaliseGenotype('ga'), 'AG');
  for (const g of ['--', '00', '0', 'NC', '', 'A/', 'XY', 'ACG']) assert.equal(normaliseGenotype(g), g === 'A/' ? 'A' : null, g);
});

// A minimal one-entry zip, deflated, like the 23andMe and AncestryDNA downloads.
function zipOf(name, text) {
  const data = Buffer.from(text);
  const comp = deflateRawSync(data);
  const nameBuf = Buffer.from(name);
  const crc = crc32(data);
  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0, 6); local.writeUInt16LE(8, 8);
  local.writeUInt32LE(crc, 14); local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(nameBuf.length, 26);
  const cen = Buffer.alloc(46);
  cen.writeUInt32LE(0x02014b50, 0); cen.writeUInt16LE(20, 4); cen.writeUInt16LE(20, 6); cen.writeUInt16LE(0, 8); cen.writeUInt16LE(8, 10);
  cen.writeUInt32LE(crc, 16); cen.writeUInt32LE(comp.length, 20); cen.writeUInt32LE(data.length, 24); cen.writeUInt16LE(nameBuf.length, 28); cen.writeUInt32LE(0, 42);
  const cenOffset = 30 + nameBuf.length + comp.length;
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(1, 8); end.writeUInt16LE(1, 10); end.writeUInt32LE(46 + nameBuf.length, 12); end.writeUInt32LE(cenOffset, 16);
  return new Blob([local, nameBuf, comp, cen, nameBuf, end]);
}

test('a zipped raw file is opened and streamed without unzipping it first', async () => {
  const text = `# rsid\tchromosome\tposition\tgenotype\nrs4988235\t2\t136608646\tAG\n${'rs1\t1\t1\tAA\n'.repeat(5000)}`;
  const blob = zipOf('genome_Test_v5_Full.txt', text);
  assert.equal(await isZip(blob), true);
  assert.equal(await isZip(new Blob(['rsid\tchromosome'])), false);
  const inner = await openRawDataInZip(blob);
  assert.equal(inner.name, 'genome_Test_v5_Full.txt');
  const r = await extractPanel(chunksOf(inner.text), WANT);
  assert.equal(r.rows, 5001);
  assert.equal(r.found.get('rs4988235').genotype, 'AG');
});
